import joblib
import pandas as pd

# Load saved model and preprocessor
model = joblib.load(
    "house_price_prediction_model.pkl"
)

preprocessor = joblib.load(
    "house_price_preprocessor.pkl"
)

# New house details
new_house = pd.DataFrame([{
    "area_type": "Super built-up Area",
    "location": "Whitefield",
    "total_sqft": 1200,
    "bath": 2,
    "balcony": 1,
    "BHK": 2,
    "sqft_per_bhk": 600
}])

# Apply the same preprocessing
processed_house = preprocessor.transform(new_house)

# Predict house price
predicted_price = model.predict(processed_house)

print("Predicted House Price:", predicted_price[0], "Lakhs")